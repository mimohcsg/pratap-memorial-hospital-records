let currentLang = localStorage.getItem('hospitalLang') || 'hi';

function t(key) {
  const keys = key.split('.');
  let val = TRANSLATIONS[currentLang];
  for (const k of keys) val = val?.[k];
  if (val === undefined) {
    let fallback = TRANSLATIONS.en;
    for (const k of keys) fallback = fallback?.[k];
    return fallback || key;
  }
  return val;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('hospitalLang', lang);
  document.documentElement.lang = lang === 'hi' ? 'hi' : 'en';
  applyTranslations();
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.hasAttribute('data-i18n-placeholder')) el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  document.querySelectorAll('option[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });

  document.title = t('pageTitle');
  document.getElementById('lang-en')?.classList.toggle('active', currentLang === 'en');
  document.getElementById('lang-hi')?.classList.toggle('active', currentLang === 'hi');

  if (typeof onLangChange === 'function') onLangChange();
  if (typeof onVoiceLangChange === 'function') onVoiceLangChange();
  if (typeof onCameraLangChange === 'function') onCameraLangChange();
}

document.addEventListener('DOMContentLoaded', () => {
  document.getElementById('lang-hi')?.addEventListener('click', () => setLang('hi'));
  document.getElementById('lang-en')?.addEventListener('click', () => setLang('en'));
  applyTranslations();
});
